# Импортируем класс datetime из модуля datetime для работы с датами и временем.
from datetime import datetime

# Импортируем функцию sqrt из модуля math для вычисления квадратного корня.
from math import sqrt


def main(**kwargs):
    """
    Функция main принимает произвольное количество именованных аргументов (**kwargs),
    где каждый аргумент представляет собой список из двух чисел.
    Для каждого такого списка функция вычисляет евклидово расстояние от начала координат
    (квадратный корень из суммы квадратов двух чисел) и выводит результат на экран.

    Аргументы:
        **kwargs: Именованные аргументы, где значение каждого — список из двух чисел.

    Возвращает:
        None (функция только печатает результаты).
    """
    # Цикл проходит по всем элементам словаря kwargs (метод items() возвращает пары ключ-значение).
    for key in kwargs.items():
        # Вычисляем квадратный корень из суммы квадратов первого и второго элементов списка (key[1] — значение, key[1][0] и key[1][1] — элементы списка).
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)
        # Выводим результат на экран с помощью функции print.
        print(result)


# Проверяем, запущен ли скрипт напрямую (не импортирован как модуль).
if __name__ == '__main__':
    # Записываем текущее время в переменную start_time для измерения времени выполнения.
    start_time = datetime.now()
    # Вызываем функцию main с передачей именованных аргументов: каждый — список из двух чисел.
    main(
        # Аргумент one: список [10, 3].
        one=[10, 3],
        # Аргумент two: список [5, 4].
        two=[5, 4],
        # Аргумент three: список [15, 13].
        three=[15, 13],
        # Аргумент four: список [93, 53].
        four=[93, 53],
        # Аргумент five: список [133, 15].
        five=[133, 15]
    )
    # Вычисляем разницу между текущим временем и start_time для получения времени выполнения.
    time_costs = datetime.now() - start_time
    # Выводим на экран строку с временем выполнения программы в формате f-строки.
    print(f"Время выполнения программы - {time_costs}")